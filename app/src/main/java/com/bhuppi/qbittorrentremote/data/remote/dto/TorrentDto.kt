package com.bhuppi.qbittorrentremote.data.remote.dto

import com.bhuppi.qbittorrentremote.domain.model.Torrent
import com.google.gson.annotations.SerializedName

data class TorrentDto(
    @SerializedName("added_on") val addedOn: Long = 0,
    @SerializedName("amount_left") val amountLeft: Long = 0,
    @SerializedName("auto_tmm") val autoTmm: Boolean = false,
    val availability: Double = 0.0,
    val category: String = "",
    val completed: Long = 0,
    @SerializedName("completion_on") val completionOn: Long = 0,
    @SerializedName("content_path") val contentPath: String = "",
    @SerializedName("dl_limit") val dlLimit: Long = 0,
    val dlspeed: Int = 0,
    val downloaded: Long = 0,
    @SerializedName("downloaded_session") val downloadedSession: Long = 0,
    val eta: Int = 0,
    @SerializedName("f_l_piece_prio") val flPiecePrio: Boolean = false,
    @SerializedName("force_start") val forceStart: Boolean = false,
    val hash: String = "",
    @SerializedName("last_activity") val lastActivity: Long = 0,
    @SerializedName("magnet_uri") val magnetUri: String = "",
    @SerializedName("max_ratio") val maxRatio: Double = 0.0,
    @SerializedName("max_seeding_time") val maxSeedingTime: Long = 0,
    val name: String = "",
    @SerializedName("num_complete") val numComplete: Int = 0,
    @SerializedName("num_incomplete") val numIncomplete: Int = 0,
    @SerializedName("num_leechs") val numLeechs: Int = 0,
    @SerializedName("num_seeds") val numSeeds: Int = 0,
    val priority: Int = 0,
    val progress: Double = 0.0,
    val ratio: Double = 0.0,
    @SerializedName("save_path") val savePath: String = "",
    @SerializedName("seeding_time") val seedingTime: Long = 0,
    @SerializedName("seen_complete") val seenComplete: Long = 0,
    @SerializedName("seq_dl") val seqDl: Boolean = false,
    val size: Long = 0,
    val state: String = "",
    @SerializedName("super_seeding") val superSeeding: Boolean = false,
    val tags: String = "",
    @SerializedName("time_active") val timeActive: Long = 0,
    @SerializedName("total_size") val totalSize: Long = 0,
    val tracker: String = "",
    @SerializedName("up_limit") val upLimit: Long = 0,
    val uploaded: Long = 0,
    @SerializedName("uploaded_session") val uploadedSession: Long = 0,
    val upspeed: Int = 0
)

fun TorrentDto.toTorrent(): Torrent {
    return Torrent(
        addedOn = addedOn,
        amountLeft = amountLeft,
        autoTmm = autoTmm,
        availability = availability,
        category = category,
        completed = completed,
        completionOn = completionOn,
        contentPath = contentPath,
        dlLimit = dlLimit,
        dlspeed = dlspeed,
        downloaded = downloaded,
        downloadedSession = downloadedSession,
        eta = eta,
        flPiecePrio = flPiecePrio,
        forceStart = forceStart,
        hash = hash,
        lastActivity = lastActivity,
        magnetUri = magnetUri,
        maxRatio = maxRatio,
        maxSeedingTime = maxSeedingTime,
        name = name,
        numComplete = numComplete,
        numIncomplete = numIncomplete,
        numLeechs = numLeechs,
        numSeeds = numSeeds,
        priority = priority,
        progress = progress,
        ratio = ratio,
        savePath = savePath,
        seedingTime = seedingTime,
        seenComplete = seenComplete,
        seqDl = seqDl,
        size = size,
        state = state,
        superSeeding = superSeeding,
        tags = tags,
        timeActive = timeActive,
        totalSize = totalSize,
        tracker = tracker,
        upLimit = upLimit,
        uploaded = uploaded,
        uploadedSession = uploadedSession,
        upspeed = upspeed
    )
}
